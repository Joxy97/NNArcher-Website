export function createEnglishTranslator(content) {
  const map = new Map(Object.entries(ui));
  const pair = (source, translated, label) => {
    if (source.length !== translated.length)
      throw new Error(`English translation count differs for ${label}: ${source.length} / ${translated.length}`);
    source.forEach((value, index) => {
      const original = typeof value === "string" ? value : value.text;
      const replacement = translated[index];
      if (map.has(original) && map.get(original) !== replacement)
        throw new Error(`Conflicting English translation for ${original}`);
      map.set(original, replacement);
    });
  };
  pair(content.home.texts, home, "home");
  pair(content.about.texts, about, "about");
  pair(content.galleries.map((g) => g.title), galleryTitles, "galleries");
  for (const kind of ["privacy", "terms"])
    pair(content.legal[kind], legal[kind], kind);
  services.forEach((source, index) => {
    const translated = serviceCopy[index];
    for (const key of ["title", "homeTitle", "description", "intro", "note"])
      if (source[key]) pair([source[key]], [translated[key]], `service ${index} ${key}`);
    source.packages.forEach((p, pIndex) => {
      const en = translated.packages[pIndex];
      for (const key of ["title", "description"])
        if (p[key]) pair([p[key]], [en[key]], `service ${index} package ${pIndex} ${key}`);
      pair(p.items, en.items, `service ${index} package ${pIndex} items`);
      if (p.extras) pair(p.extras, en.extras, `service ${index} package ${pIndex} extras`);
    });
  });
  return (text) => map.get(text) ?? text;
}
